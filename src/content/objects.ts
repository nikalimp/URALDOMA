// «ЖК «Тринити»» → «в ЖК «Тринити»», «Жилой район «Солнечный»» → «в жилом районе «Солнечный»»
export function inName(name: string) {
  const rules: [RegExp, string][] = [
    [/^Жилой район /, "жилом районе "],
    [/^Жилой комплекс /, "жилом комплексе "],
    [/^Жилая экосистема /, "жилой экосистеме "],
    [/^Квартал /, "квартале "],
    [/^Жилой дом /, "доме "],
    [/^Микрорайон /, "микрорайоне "],
  ];
  for (const [re, to] of rules) if (re.test(name)) return name.replace(re, to);
  return name;
}

const has = (v?: string | null): v is string => Boolean(v && v.trim());
const lower = (s: string) => s.charAt(0).toLowerCase() + s.slice(1);

// Технология ремонта по типу конструкции — общие правила, без цифр о конкретном доме
function frameText(frame?: string | null) {
  const f = (frame ?? "").toLowerCase();
  if (f.includes("панел")) return "В панельном доме несущие — стены из панелей: проёмы в них не прорезают, а перепланировка сводится к переносу лёгких перегородок. Горизонтальные штробы в несущих панелях запрещены, поэтому проводку ведут по перегородкам, потолку или в стяжке — это закладываем в проект электрики заранее.";
  if (f.includes("монолит")) return "Монолитный каркас держится на колоннах, пилонах и части стен, межкомнатные перегородки обычно не несущие. Это даёт свободу в планировке, но бетон режут алмазным инструментом, а несущие элементы ослаблять нельзя. Поэтому трассы электрики и сантехники считаем по дизайн-проекту до начала работ — чтобы не штробить бетон дважды.";
  if (f.includes("кирпич")) return "В кирпичном доме несущие — наружные и часть внутренних стен: их не ослабляют проёмами без проекта и согласования. Кирпич хорошо держит тепло и звук, а штробы в нём делают проще, чем в бетоне; трассы всё равно согласуем с проектом электрики.";
  return "Тип конструкции влияет на то, какие стены можно переносить и где вести трассы электрики и сантехники. Его проверяем по документам дома на замере и закладываем в проект до начала работ.";
}

function finishingText(fin?: string | null) {
  const f = (fin ?? "").toLowerCase();
  const parts: string[] = [];
  if (/white|предчист/.test(f)) parts.push("В предчистовой отделке («white box») стяжка и штукатурка уже есть: перед чистовой мы проверяем геометрию стен и пола и переносим выводы электрики и сантехники, если они не совпадают с проектом.");
  if (/без отдел|черн/.test(f)) parts.push("Квартиру без отделки делаем с нуля: стяжка, штукатурка и разводка — сразу под ваш проект, без демонтажа.");
  if (/с отделк|чистов|под ключ/.test(f) && !/без отдел/.test(f)) parts.push("Если квартира с отделкой от застройщика и она не устраивает, её демонтируют — это добавляет работы в смету, зато инженерию часто удаётся сохранить.");
  if (!parts.length) return "С чего начнётся ремонт, зависит от того, в каком виде сдана квартира: без отделки, в предчистовой отделке или с отделкой от застройщика. Это смотрим на замере.";
  return parts.join(" ");
}

function ceilingText(c?: string | null) {
  const n = parseFloat((c ?? "").replace(",", ".").match(/\d+[.,]?\d*/)?.[0] ?? "");
  if (!n) return null;
  if (n >= 3) return "Высокие потолки дают место для скрытого карниза, световых линий и ниш под вентиляцию без потери высоты.";
  if (n >= 2.7) return "При потолках около 2,7 м свет и карнизы встраивают «в плоскость», чтобы не съедать высоту комнат.";
  return "При невысоких потолках избегаем многоуровневых конструкций: свет — встроенный или трековый, карниз — скрытый.";
}

const facts = (f: ObjectFacts): [string, string][] =>
  (f.kind === "zk"
    ? [["Застройщик", f.developer], ["Район", f.district], ["Адрес", f.address], ["Сдача", f.years], ["Класс", f.class], ["Конструкция", f.frame], ["Этажность", f.floors], ["Потолки", f.ceiling], ["Отделка от застройщика", f.finishing], ["Отопление", f.heating]]
    : [["Девелопер", f.developer], ["Где", f.location], ["Застройка", f.years], ["Размер", f.size], ["Дома", f.houses], ["Коммуникации", f.utilities], ["Отделка", f.finishing]]
  ).filter((x): x is [string, string] => has(x[1]));

export function factsTable(f: ObjectFacts) {
  return facts(f);
}

