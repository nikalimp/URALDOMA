export type Pic = { key: string; base: string; caption: string; alt: string; place: string; href: string; wide: boolean };

// Фото по ключу "slug/NN": путь без расширения, подпись, alt с местом съёмки, ссылка на объект
export function pic(key: string): Pic {
  const [slug, n] = key.split("/");
  const c = caseBySlug(slug);
  const caption = captions[slug]?.[Number(n) - 1] ?? "";
  const place = c?.place ?? "";
  return { key, base: `/images/objects/${slug}/${n}`, caption, alt: place ? `${caption} — ${place}` : caption, place, href: `/portfolio/${slug}/`, wide: WIDE.has(key) };
}

export const picsOf = (slug: string) => (captions[slug] ?? []).map((_, i) => pic(`${slug}/${String(i + 1).padStart(2, "0")}`));
